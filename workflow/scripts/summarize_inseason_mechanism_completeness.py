BASE = ROOT / 'visualize/paper_experiments'
TEX = ROOT / 'Paper/iclr2027/sections'
NAMES = dict(full='Full terminal input', no_weather='No terminal weather',
    no_quality='No terminal product support', no_weather_quality='Neither terminal path')
COORDINATES = dict(packed='Packed active slots', calendar='Natural-month coordinates')
MODEL_NAMES = dict(cnn_rnn='CNN--RNN (adapted)', transformer='Transformer')


def table(name, caption, label, columns, header, rows):
    (TEX / name).write_text('% Generated by scripts/summarize_inseason_mechanism_completeness.py\n'
        '\\begin{table}[htbp]\n\\centering\\small\n'+f'\\caption{{{caption}}}\n\\label{{{label}}}\n'
        +f'\\begin{{tabular}}{{{columns}}}\n\\toprule\n'+header+r' \\'+'\n\\midrule\n'
        +'\n'.join(rows)+'\n\\bottomrule\n\\end{tabular}\n\\end{table}\n')


def labels_for(raw):
    return {k: np.concatenate([raw[k][partition(raw, c)['evaluation']] for c in BLOCKS]) for k in LABELS}


def load_predictions(path, raw, indices):
    with np.load(path) as saved:
        for key in LABELS:
            np.testing.assert_array_equal(saved[key], raw[key][indices])
        return saved['prediction'].copy()


def measured(labels, prediction, identity):
    metric = complete_score(labels, prediction)
    row = dict(**identity, mean_annual_rmse=metric['mean_annual_rmse'], pooled_rmse=metric['pooled_rmse'])
    annual = [dict(**identity, year=int(year), rmse=value) for year, value in metric['per_year_rmse'].items()]
    return row, annual


def collect_terminal():
    rows, annual, pairs, completion, registry, sources = [], [], [], [], [], {}
    for crop in RECIPES:
        raw, _ = load(crop)
        labels = labels_for(raw)
        predictions = {(condition, round(100*r), mode): [] for condition in CONDITIONS for r in RATIOS for mode in MODES}
        for cutoff in BLOCKS:
            root = terminal_root(crop, cutoff)
            marker = verify(root)
            if marker['smoke'] or not marker['full_rebuild_verified']:
                raise ValueError('Missing original terminal reconstruction')
            sources[str(root / 'complete.json')] = sha256(root / 'complete.json')
            cfg = json.loads((root / 'config.json').read_text())
            if (cfg['crop'], cfg['cutoff'], cfg['seed'], cfg['recipe']) != (crop, cutoff, 42, RECIPES[crop]):
                raise ValueError('Wrong terminal configuration identity')
            for path, digest in cfg['sources'].items():
                if sha256(Path(path)) != digest:
                    raise ValueError('Changed original terminal source')
                sources[path] = digest
            index = partition(raw, cutoff)['evaluation']
            for condition in CONDITIONS:
                dest = root / condition
                verify(dest)
                records = json.loads((dest / 'metrics.json').read_text())['fits']
                for branch in records:
                    weight = dest / branch['branch'] / 'model.joblib'
                    model = joblib.load(weight)
                    removed = check_splits(model, condition)
                    if removed != branch['removed_columns'] or model.get_params() != branch['parameters']:
                        raise ValueError('Changed terminal mask or tree parameters')
                    if condition == 'full' and branch['original_prediction_max_error'] > 1e-12:
                        raise ValueError('Original terminal prediction was not reconstructed')
                    registry.append(dict(crop=crop, cutoff=cutoff, condition=condition, branch=branch['branch'],
                        weight=str(weight), sha256=sha256(weight), config=str(root / 'config.json'),
                        removed_columns=json.dumps(removed), full_rebuild_error=branch['original_prediction_max_error']))
                for ratio in RATIOS:
                    percent = round(100*ratio)
                    for mode in MODES:
                        path = dest / f'tail_{percent:02d}_{mode}.npz'
                        prediction = load_predictions(path, raw, index)
                        if condition == 'full':
                            expected = np.load(CACHE / crop / f'world_{cutoff}_{RECIPES[crop]}_{mode}_{percent:03d}.npy')
                            np.testing.assert_allclose(prediction, expected, rtol=0, atol=1e-12)
                        predictions[condition, percent, mode].append(prediction)
                        sources[str(path)] = sha256(path)
        predictions = {key: np.concatenate(value) for key, value in predictions.items()}
        for (condition, percent, mode), prediction in predictions.items():
            row, years = measured(labels, prediction, dict(crop=crop, condition=condition, percent=percent, mode=mode))
            rows.append(row)
            annual.extend(years)
            if condition != 'full':
                pairs.append(dict(crop=crop, removed=condition, percent=percent, mode=mode,
                    **annual_gain(labels['target'], predictions['full', percent, mode], prediction, labels['year'])))
            if mode == 'biid':
                completion.append(dict(crop=crop, condition=condition, percent=percent,
                    **annual_gain(labels['target'], prediction, predictions[condition, percent, 'climatology'], labels['year'])))
    if len(registry) != 60 or len(rows) != 96 or len(completion) != 48:
        raise ValueError('Incomplete terminal-path matrix')
    return pd.DataFrame(rows), pd.DataFrame(annual), pd.DataFrame(pairs), pd.DataFrame(completion), registry, sources


def collect_calendar():
    rows, annual, pairs, registry, sources = [], [], [], [], {}
    for crop in RECIPES:
        raw, _ = load(crop)
        labels = labels_for(raw)
        for model in MODELS:
            predictions = {coordinate: [] for coordinate in COORDINATES}
            for cutoff in BLOCKS:
                root = calendar_root(crop, cutoff, model)
                marker = verify(root)
                if marker['smoke'] or not marker['original_prediction_replayed'] or not marker['normalization_matched']:
                    raise ValueError('Missing coordinate identity/replay evidence')
                original = reference_root(crop, cutoff, model)
                cfg = json.loads((root / 'config.json').read_text())
                if cfg['reference_marker_sha256'] != sha256(original / 'complete.json'):
                    raise ValueError('Changed original packed reference')
                old_marker = json.loads((original / 'complete.json').read_text())
                check_files(original, old_marker['files'])
                for name, digest in old_marker['code_sha256'].items():
                    if sha256(ROOT / 'scripts' / name) != digest:
                        raise ValueError('Changed original coordinate training source')
                if old_marker['smoke'] or (cfg['crop'], cfg['cutoff'], cfg['model'], cfg['ratio']) != (crop, cutoff, model, .1):
                    raise ValueError('Incorrect coordinate configuration identity')
                sources[str(root / 'complete.json')] = sha256(root / 'complete.json')
                sources[str(original / 'complete.json')] = sha256(original / 'complete.json')
                old = original / 'tail_10'
                for filename in ('inner_normalization.json', 'metrics.json'):
                    new_norm = json.loads((root / filename).read_text())
                    old_norm = json.loads((old / filename).read_text())
                    if filename == 'metrics.json':
                        new_norm, old_norm = new_norm['full_normalization'], old_norm['full_normalization']
                    if new_norm != old_norm:
                        raise ValueError('Changed normalization between temporal coordinates')
                old_state = torch.load(old / 'model.pt', map_location='cpu', weights_only=True)
                new_state = torch.load(root / 'model.pt', map_location='cpu', weights_only=True)
                if {k: tuple(v.shape) for k, v in old_state.items()} != {k: tuple(v.shape) for k, v in new_state.items()}:
                    raise ValueError('Temporal comparison changed model capacity')
                params = sum(v.numel() for v in new_state.values())
                index = partition(raw, cutoff)['evaluation']
                for coordinate, dest in [('packed', old), ('calendar', root)]:
                    path = dest / 'evaluation_predictions.npz'
                    predictions[coordinate].append(load_predictions(path, raw, index))
                    sources[str(path)] = sha256(path)
                    registry.append(dict(crop=crop, cutoff=cutoff, model=model, coordinate=coordinate,
                        weight=str(dest / 'model.pt'), sha256=sha256(dest / 'model.pt'),
                        config=str((original if coordinate == 'packed' else root) / 'config.json'),
                        parameter_elements=params, normalization_matched=True))
            predictions = {key: np.concatenate(value) for key, value in predictions.items()}
            for coordinate, prediction in predictions.items():
                row, years = measured(labels, prediction, dict(crop=crop, model=model, coordinate=coordinate))
                rows.append(row)
                annual.extend(years)
            pairs.append(dict(crop=crop, model=model,
                **annual_gain(labels['target'], predictions['packed'], predictions['calendar'], labels['year'])))
    if len(registry) != 48 or len(rows) != 16:
        raise ValueError('Incomplete coordinate matrix')
    return pd.DataFrame(rows), pd.DataFrame(annual), pd.DataFrame(pairs), registry, sources


def plot_terminal(frame, out):
    fig, axes = plt.subplots(2, 2, figsize=(10, 7.2))
    fig.subplots_adjust(left=.10, right=.97, bottom=.18, top=.95, hspace=.43, wspace=.28)
    for crop, ax in zip(RECIPES, axes.flat):
        for condition, color in zip(CONDITIONS, ('#1c7c68', '#3267a3', '#b7673d', '#777777')):
            sub = frame[frame.crop.eq(crop) & frame.condition.eq(condition) & frame['mode'].eq('biid')].sort_values('percent')
            ax.plot(sub.percent, sub.mean_annual_rmse, 'o-', color=color, label=NAMES[condition], markersize=4)
        ax.set_title(crop.title()+' | '+RECIPES[crop].upper().replace('_', ' + '), fontsize=11)
        ax.set_xticks([10, 30, 50])
        ax.set_xlabel('Nominal unobserved suffix (%)')
        ax.set_ylabel('Mean annual yield RMSE (t/ha)')
        ax.spines[['top', 'right']].set_visible(False)
        ax.grid(axis='y', alpha=.2)
    fig.legend(*axes.flat[0].get_legend_handles_labels(), loc='lower center', ncol=2, frameon=False)
    for ext in ('png', 'pdf'):
        fig.savefig(out / f'terminal_path_comparison.{ext}', dpi=220, bbox_inches='tight')
    plt.close(fig)


