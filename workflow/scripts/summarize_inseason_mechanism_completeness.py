def main(study):
    plt.rcParams.update({'font.family':'DejaVu Sans', 'font.size':10, 'pdf.fonttype':42})
    out = BASE / ('inseason_terminal_paths_v1' if study == 'terminal' else 'inseason_calendar_coordinates_v1')
    out.mkdir(parents=True, exist_ok=True)
    if study == 'terminal':
        frame, annual, paired, completion, registry, sources = collect_terminal()
        completion.to_csv(out / 'completion_gains.csv', index=False)
        export_terminal(frame, paired, completion, out)
    else:
        frame, annual, paired, registry, sources = collect_calendar()
        export_calendar(frame, paired, out)
    for name, data in [('scores',frame),('annual',annual),('paired_gains',paired),('checkpoint_registry',pd.DataFrame(registry))]:
        data.to_csv(out / (name+'.csv'), index=False)
    atomic_json(out / 'audit.json', dict(study=study, sources=sources, seed=42,
        all_thirteen_years=True, all_registered_conditions=True, weight_records=len(registry),
        new_branch_fits=60 if study == 'terminal' else 24,
        original_rebuilds=15 if study == 'terminal' else 0,
        original_models_reused=0 if study == 'terminal' else 24,
        generator_sha256=sha256(Path(__file__))))
    print(frame.to_string(index=False), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--study', choices=('terminal','calendar'), required=True)
    main(parser.parse_args().study)
